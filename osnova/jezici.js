// ===== FUNKCIJE ZA PREVOD =====
function trenutniJezik() {
    try {
        if (typeof podaciAplikacije !== 'undefined' && podaciAplikacije && podaciAplikacije.settings && podaciAplikacije.settings.language === 'sr') return 'sr';
    } catch (e) { }
    return 'en';
}

function t(kljuc, promenljive) {
    const jezik = trenutniJezik();
    let tekst = null;
    if (PREDVODI[jezik] && Object.prototype.hasOwnProperty.call(PREDVODI[jezik], kljuc)) {
        tekst = PREDVODI[jezik][kljuc];
    } else if (PREDVODI.sr && Object.prototype.hasOwnProperty.call(PREDVODI.sr, kljuc)) {
        tekst = PREDVODI.sr[kljuc];
    } else if (PREDVODI.en && Object.prototype.hasOwnProperty.call(PREDVODI.en, kljuc)) {
        tekst = PREDVODI.en[kljuc];
    }
    if (tekst == null) tekst = String(kljuc);

    if (promenljive && typeof promenljive === 'object') {
        Object.keys(promenljive).forEach(k => {
            tekst = tekst.split('{' + k + '}').join(String(promenljive[k]));
        });
    }
    return tekst;
}

function jeSrpski() {
    return trenutniJezik() === 'sr';
}

function pluralCasovi(n) {
    if (jeSrpski()) return n === 1 ? '\u010das' : (n >= 2 && n <= 4 ? '\u010dasa' : '\u010dasova');
    return n === 1 ? 'period' : 'periods';
}

function tekstDana(n) {
    if (n === 0) return t('vreme.danas');
    if (n === 1) return t('vreme.sutra');
    return t('vreme.dana', { n: n });
}

