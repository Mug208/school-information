function osveziLokalneKonstante() {
    DANI_LAT = [t('dani.pon'), t('dani.uto'), t('dani.sre'), t('dani.cet'), t('dani.pet'), t('dani.sub'), t('dani.ned')];
    DANI_KRATKO = [t('daniK.pon'), t('daniK.uto'), t('daniK.sre'), t('daniK.cet'), t('daniK.pet'), t('daniK.sub'), t('daniK.ned')];
    MESECI_LAT = [t('mesec.1'), t('mesec.2'), t('mesec.3'), t('mesec.4'), t('mesec.5'), t('mesec.6'),
        t('mesec.7'), t('mesec.8'), t('mesec.9'), t('mesec.10'), t('mesec.11'), t('mesec.12')];
    DANI_ROTACIJE = [...DANI_LAT];
    DANI_ROTACIJE_INSTRUMENTAL = DANI_LAT.map(d => t('bios.sm.instrumental', { dan: d.toLowerCase() }));
    NAZIVI_ROTACIJE = { nedelja: t('rot.nedelja'), mesec: t('rot.mesec'), polugodiste: t('rot.polugodiste'), godina: t('rot.godina') };
    TEKST_PRECICA = t('precice.tekst');

    const tipovi = [['kontrolni', 'tip.kontrolni', 'tipK.kontrolni'], ['pismeni', 'tip.pismeni', 'tipK.pismeni'],
        ['blic', 'tip.blic', 'tipK.blic'], ['prezentacija', 'tip.prezentacija', 'tipK.prezentacija'],
        ['domaci', 'tip.domaci', 'tipK.domaci'], ['ostalo', 'tip.ostalo', 'tipK.ostalo']];
    tipovi.forEach(([id, kljuc, kljucK]) => {
        if (TIPOVI_BELESKE[id]) {
            TIPOVI_BELESKE[id].label = t(kljuc);
            TIPOVI_BELESKE[id].shortLabel = t(kljucK);
        }
    });
}

function primeniPrevodeNaDOM(koren) {
    const dom = koren || document;

    dom.querySelectorAll('[data-i18n]').forEach(el => {
        el.textContent = t(el.getAttribute('data-i18n'));
    });
    dom.querySelectorAll('[data-i18n-html]').forEach(el => {
        el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    dom.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    dom.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    dom.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
    });
}

function postaviJezik(jezik, opcije) {
    const opc = opcije || {};
    const novi = jezik === 'sr' ? 'sr' : 'en';

    podaciAplikacije.settings.language = novi;
    document.documentElement.setAttribute('lang', novi);
    osveziLokalneKonstante();
    primeniPrevodeNaDOM();

    if (opc.sacuvaj !== false) {
        sacuvajPodatke();
    }
    if (opc.osvezi !== false) {
        prikaziSve();
        azurirajMultiSelectUI();

        try {
            if (window.BIOS && typeof window.BIOS.otvoren === 'function' && window.BIOS.otvoren()) {
                if (typeof renderNav === 'function') renderNav();
                if (typeof osveziPrikaz === 'function') osveziPrikaz();
            }
        } catch (e) { }
    }
    return novi;
}

